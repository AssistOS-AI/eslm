import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { PROCESSING_GRAPH_CATALOG } from '../../src/processing-graph/index.mjs';
import { BUILTIN_STRATEGY_CATALOG } from '../../src/strategy/builtin-strategy-catalog.mjs';
import { buildHomepageProcessingGraphProjection } from './processing-graph-explorer-model.mjs';

const outputUrl = new URL('./processing-graph-explorer-data.mjs', import.meta.url);
const projection = buildHomepageProcessingGraphProjection(
  PROCESSING_GRAPH_CATALOG,
  BUILTIN_STRATEGY_CATALOG,
);
const source = `// Generated by docs/assets/generate-processing-graph-explorer-data.mjs.
// Do not edit this catalog projection by hand.
export const HOMEPAGE_PROCESSING_GRAPH_PROJECTION = Object.freeze(${JSON.stringify(projection, null, 2)});
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputUrl, 'utf8');
  if (current !== source) {
    throw new Error('The checked-in processing-graph explorer projection is stale. Regenerate it.');
  }
  process.stdout.write(`current ${fileURLToPath(outputUrl)}\n`);
} else {
  await writeFile(outputUrl, source, 'utf8');
  process.stdout.write(`${fileURLToPath(outputUrl)}\n`);
}
